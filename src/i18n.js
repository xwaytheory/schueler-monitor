const TABLES = { pl: PL, en: EN };

/** Tłumaczenie klucza z podstawianiem {zmiennych}. */
export function t(lang, key, vars = {}) {
  const table = TABLES[normalizeLang(lang)] || TABLES.pl;
  const raw = table[key] ?? TABLES.pl[key] ?? key;
  return String(raw).replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ''));
}

/** Odmiana rzeczownika po liczbie (PL: 1/2–4/5+, EN: 1/2+). */
export function pluralFor(lang, n, forms) {
  const abs = Math.abs(Number(n) || 0);
  if (normalizeLang(lang) === 'en') return abs === 1 ? forms.one : forms.many;
  const last = abs % 10;
  const lastTwo = abs % 100;
  if (abs === 1) return forms.one;
  if (last >= 2 && last <= 4 && !(lastTwo >= 12 && lastTwo <= 14)) return forms.few ?? forms.many;
  return forms.many;
}
